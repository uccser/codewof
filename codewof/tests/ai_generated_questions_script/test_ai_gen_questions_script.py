def make_question(slug="new-question", concepts=("ai-generated", "functions"), outputs=3, **overrides):
    """Build a valid generated question (as the model would return it), with optional overrides."""
    files = {
        "question.md": f"# {slug}\n\nA description.\n",
        "solution.py": "print('hello')\n",
    }
    for number in range(1, outputs + 1):
        files[f"test-case-{number}-code.txt"] = f"print({number})\n"
        files[f"test-case-{number}-output.txt"] = f"{number}\n"
    concept_lines = "".join(f"    - {concept}\n" for concept in concepts)
    yaml_segment = (
        f"{slug}:\n"
        "  types:\n"
        "    - function\n"
        "  difficulty: difficulty-0\n"
        "  concepts:\n"
        f"{concept_lines}"
        "  contexts:\n"
        "    - simple-mathematics"
    )
    question = {"folder_name": slug, "files": files, "yaml_segment": yaml_segment}
    question.update(overrides)
    return question


