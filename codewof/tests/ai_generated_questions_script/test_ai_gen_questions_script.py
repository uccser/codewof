def call_quietly(func, *args, **kwargs):
    """Call a function, returning (result, printed_output) and keeping the test output clean."""
    buffer = io.StringIO()
    with redirect_stdout(buffer):
        result = func(*args, **kwargs)
    return result, buffer.getvalue()


